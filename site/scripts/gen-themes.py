#!/usr/bin/env python3
"""Regenerate site/assets/themes-data.js from the GUI's built-in themes.

Run from the repository root after editing crates/tuner-gtk/src/themes.rs:

    python3 site/scripts/gen-themes.py
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
src = (root / "crates/tuner-gtk/src/themes.rs").read_text()
body = src.split("pub const ALL", 1)[1]

themes = []
for block in re.findall(r"Builtin \{(.*?)\n    \}", body, re.S):
    fields = dict(re.findall(r"(\w+): (\"[^\"]*\"|true|false)", block))
    themes.append(
        {
            "name": json.loads(fields["name"]),
            "label": json.loads(fields["label"]),
            "dark": fields["dark"] == "true",
            "bg": json.loads(fields["background"]),
            "bgDark": json.loads(fields["dark_background"]),
            "bgDarker": json.loads(fields["darker_background"]),
            "bgLight": json.loads(fields["lighter_background"]),
            "fg": json.loads(fields["foreground"]),
            "fgDim": json.loads(fields["dark_foreground"]),
            "fgBright": json.loads(fields["bright_foreground"]),
            "accent": json.loads(fields["accent"]),
            "sel": json.loads(fields["selection"]),
            "muted": json.loads(fields["muted"]),
            "warn": json.loads(fields["warning"]),
            "err": json.loads(fields["error"]),
        }
    )

out = root / "site/assets/themes-data.js"
out.write_text(
    "// Generated by site/scripts/gen-themes.py from crates/tuner-gtk/src/themes.rs. Do not edit.\n"
    "window.TUNER_THEMES = "
    + json.dumps(themes, ensure_ascii=False, indent=1)
    + ";\n"
)
print(f"wrote {len(themes)} themes to {out.relative_to(root)}")
